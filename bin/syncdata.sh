#!/bin/bash -eu

# Pull data files from one of my HandyNotes plugins into Data/<Expansion>/.
#
#   bin/syncdata.sh WarWithin ../HandyNotes_WarWithin
#   bin/syncdata.sh WarWithin ../HandyNotes_WarWithin --dry-run
#
# Data/<Expansion>/sync.files lists what to copy, one entry per line relative to
# the plugin root. An entry is either a literal path (which must exist) or a
# shell glob like `zones/*` (which must match something); a glob expands against
# the plugin checkout, sorted, in place. `#` comments and blank lines are
# ignored. Files land verbatim except that a `[coord] = { -- Some Name` label
# comment becomes a real `label="Some Name"` key, so the Browser has names
# without a live lookup. The miner's ` +N` "has N other coordinates" tag is
# dropped from the name first.
#
# module.lua (the curated RegisterMobData/RegisterTreasureData) is
# SilverDragon-specific and never written here. module.xml is regenerated from
# sync.files: constants.lua and module.lua first, then the copied files in
# manifest order. Data/module.xml <Include>s it.

cd "$(dirname "$0")/.."

EXP=${1:?expansion folder name, e.g. WarWithin}
PLUGIN=${2:?path to the plugin checkout}
DRYRUN=${3:-}
PLUGIN=${PLUGIN%/}

DEST=Data/$EXP
MANIFEST=$DEST/sync.files

[ -d "$PLUGIN" ]   || { echo >&2 "no plugin checkout at $PLUGIN"; exit 1; }
[ -f "$MANIFEST" ] || { echo >&2 "no manifest at $MANIFEST"; exit 1; }

# Refuse only if something this script would overwrite is dirty. sync.files is
# an input you often edit right before running, and module.lua is never touched.
written=( "$DEST" ":(exclude)$DEST/sync.files" ":(exclude)$DEST/module.lua" )
if [ -z "$DRYRUN" ] && { ! git diff --quiet -- "${written[@]}" || ! git diff --cached --quiet -- "${written[@]}"; }; then
	echo >&2 "$DEST has uncommitted changes to files syncdata.sh writes; commit or stash them (or pass --dry-run)"
	exit 1
fi

# Resolve the manifest to a plugin-relative file list. Order follows the
# manifest; a glob contributes its matches sorted, in place, deduped.
files=()
add() {
	local p=$1 seen
	[ -f "$PLUGIN/$p" ] || return 0 # a glob can match directories; skip them
	for seen in "${files[@]}"; do
		[ "$seen" = "$p" ] && return 0
	done
	files+=("$p")
}
while IFS= read -r line || [ -n "$line" ]; do
	line=${line%%#*}                  # strip comment
	line=${line//[$' \t\r']/}         # strip whitespace (no path here has any)
	[ -n "$line" ] || continue
	case $line in
		*'*'* | *'?'* | *'['*)
			shopt -s nullglob
			matches=( "$PLUGIN"/$line )
			shopt -u nullglob
			[ ${#matches[@]} -gt 0 ] || { echo >&2 "no plugin file matches: $line"; exit 1; }
			for m in "${matches[@]}"; do add "${m#"$PLUGIN"/}"; done
			;;
		*)
			[ -f "$PLUGIN/$line" ] || { echo >&2 "missing in plugin: $line"; exit 1; }
			add "$line"
			;;
	esac
done < "$MANIFEST"

[ ${#files[@]} -gt 0 ] || { echo >&2 "$MANIFEST resolved to no files"; exit 1; }

# Warn if the plugin .toc lists a zones/ or shared/ file the sync doesn't carry.
toc_data=$(grep -ohiE '^(zones|shared)\\[A-Za-z0-9_]+\.lua' "$PLUGIN"/*.toc \
           | tr 'A-Z\\' 'a-z/' | sort -u || true)
missing=$(comm -23 <(printf '%s\n' "$toc_data") \
                   <(printf '%s\n' "${files[@]}" | tr 'A-Z' 'a-z' | sort -u) || true)
if [ -n "$missing" ]; then
	echo >&2 "note: plugin .toc lists data files not synced:"
	printf >&2 '  %s\n' $missing
fi

# `[12345678] = { -- Some Name`  ->  `[12345678] = { label="Some Name",`
# The plugin convention is exactly `{ -- Name`; require the space so `--- x`
# and `{ --note` stay comments, and skip names with a quote in them.
# striptag runs first: the miner ends the comment with ` +N` when the mob has N
# other coordinates, which is a reader's note, not part of the name.
striptag='s|^([[:space:]]*\[[0-9]+\][[:space:]]*=[[:space:]]*\{[[:space:]]*-- [^"]*[^"[:space:]])[[:space:]]+\+[0-9]+[[:space:]]*$|\1|'
labelfix='s|^([[:space:]]*\[[0-9]+\][[:space:]]*=[[:space:]]*\{)[[:space:]]*-- ([^"]*[^"[:space:]])[[:space:]]*$|\1 label="\2",|'

for rel in "${files[@]}"; do
	if [ -n "$DRYRUN" ]; then
		echo "would copy $rel"
		continue
	fi
	mkdir -p "$DEST/$(dirname "$rel")"
	# tr strips CR: the plugin checkouts are CRLF, and these land LF here.
	if [ "$rel" = "constants.lua" ]; then
		tr -d '\r' < "$PLUGIN/$rel" > "$DEST/$rel"
	else
		sed -E -e "$striptag" -e "$labelfix" "$PLUGIN/$rel" | tr -d '\r' > "$DEST/$rel"
	fi
done

if [ -z "$DRYRUN" ]; then
	{
		printf '<Ui xsi:schemaLocation="http://www.blizzard.com/wow/ui/\n..\\FrameXML\\UI.xsd">\n'
		echo '  <!-- Generated by bin/syncdata.sh from sync.files. constants.lua (if any)'
		echo '       and the curated module.lua load first, then the copied files. -->'
		# constants.lua, if the manifest carries one, then the curated module.lua.
		for rel in "${files[@]}"; do
			[ "$rel" = "constants.lua" ] && echo '  <Script file="constants.lua"/>'
		done
		echo '  <Script file="module.lua"/>'
		for rel in "${files[@]}"; do
			[ "$rel" = "constants.lua" ] && continue
			printf '  <Script file="%s"/>\n' "$rel"
		done
		echo '</Ui>'
	} > "$DEST/module.xml"

	git add "$DEST"
	echo
	echo "staged. review:  git diff --cached -- $DEST"
	echo "lint:            wsl.exe -e bash -lc 'cd /mnt/c/src/wow/SilverDragon && luacheck . --no-color -q'"
fi
